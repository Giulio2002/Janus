#!/usr/bin/env python3
"""Generate JanusX86/JanusX86/Proofs/AluWidth.lean: the per-width run lemmas of the model's ALU flag
specifications (gpr_{add,adc,sub,sbb,and,or,xor}_spec_{1,2,4,8} and their cf/pf/af/sf/of helpers),
proved against Janus' addFlags/subFlags/logicFlags (closed forms in AluSpec.lean).

The model has one copy of each function per operand size (with the size's literals), so the
lemmas are instances of one template per width. Usage: gen_aluspec.py > AluWidth.lean"""
import sys

W = [8, 16, 32, 64]
out = []
P = out.append
P('''import JanusX86.Proofs.AluSpec

/-! # Per-width ALU specifications (generated by JanusX86/tools/gen_aluspec.py; do not edit)

For each operand size `w ∈ {8, 16, 32, 64}` (the model's `_1`/`_2`/`_4`/`_8` and `…8`/`…16`/`…32`/`…64`
functions): the flag helpers as closed formulas, then `gpr_add/adc/sub/sbb/and/or/xor_spec` as
Janus' `addFlags`/`subFlags`/`logicFlags`. -/

set_option linter.unusedSimpArgs false

namespace JanusX86.Proofs
open X86Sail X86Sail.Functions
''')
for w in W:
    n = w // 8
    P(f'''
/-! ## {w}-bit -/

theorem ipow_{w} : (2 : Int) ^ ({w} : Int) = (({2**w} : Nat) : Int) := by decide +kernel
theorem ipow_{w}m : (2 : Int) ^ (({w} : Int) - 1) = (({2**(w-1)} : Nat) : Int) := by decide +kernel

theorem run_cf_spec{w} (v : BitVec {w+1}) (s : SState) :
    (cf_spec{w} v).run s = .ok (BitVec.ofBool (decide (v.toNat ≥ 2 ^ {w}))) s := by
  simp only [cf_spec{w}, unsigned_byte_p_int, run_bind,
    run_sail_assert_of (show decide (({w} : Int) ≥ 0) = true by decide), run_pure, ipow_{w}]
  refine congrArg (EStateM.Result.ok · s) (bool_to_bits_of _ _ ?_)
  generalize hx : Sail.BitVec.toNatInt v = X
  have : X = v.toNat := by rw [← hx]; rfl
  subst this
  (rw [Bool.eq_iff_iff]; simp) <;> omega

theorem run_of_spec{w} (v : BitVec {w+1}) (s : SState) :
    (of_spec{w} v).run s = .ok (BitVec.ofBool (decide ¬(-(2 ^ {w-1} : Int) ≤ v.toInt ∧ v.toInt < 2 ^ {w-1}))) s := by
  simp only [of_spec{w}, signed_byte_p_int, run_bind,
    run_sail_assert_of (show decide (({w} : Int) ≥ 0) = true by decide), run_pure, ipow_{w}m]
  refine congrArg (EStateM.Result.ok · s) (bool_to_bits_of _ _ ?_)
  generalize v.toInt = X
  (rw [Bool.eq_iff_iff]; simp) <;> omega

theorem run_pf_spec{w} (r : BitVec {w}) (s : SState) :
    (pf_spec{w} r).run s = .ok (BitVec.ofBool (Janus.Amd64.parity r.toNat)) s := by
  have hl : (Sail.BitVec.toNatInt ({'r' if w == 8 else 'loghead_bits 8 r'})) = ((r.toNat % 256 : Nat) : Int) := by
    simp [Sail.BitVec.toNatInt{', loghead_bits, sail_mask, Sail.BitVec.truncate, Sail.BitVec.length' if w > 8 else ''}]{'; omega' if w == 8 else ''}
  simp only [pf_spec{w}, hl]
  rw [pf_eq _ (by omega), parity_mod256]

theorem sf_spec{w}_eq (r : BitVec {w}) : sf_spec{w} r = BitVec.ofBool (decide (2 ^ {w-1} ≤ r.toNat)) := by
  simp only [sf_spec{w}, Sail.BitVec.extractLsb, extractLsb_one_eq_ofBool, BitVec.setWidth_eq]
  apply congrArg BitVec.ofBool
  rw [show r.getLsbD {w-1} = r.getLsbD ({w} - 1) from rfl, ← BitVec.msb_eq_getLsbD_last, BitVec.msb_eq_decide]
''')
for w in W:
    n = w // 8
    P(f'''
/-! ## {w}-bit specifications -/

theorem add_af_spec{w}_eq (x y : BitVec {w}) :
    add_af_spec{w} x y = BitVec.ofBool (decide (x.toNat % 16 + y.toNat % 16 > 15)) := by
  simp only [add_af_spec{w}, toNatInt_extract30]
  exact bool_to_bits_of _ _ (af_add_gen _ _ (by omega) (by omega))

theorem sub_af_spec{w}_eq (x y : BitVec {w}) :
    sub_af_spec{w} x y = BitVec.ofBool (decide (x.toNat % 16 < y.toNat % 16)) := by
  simp only [sub_af_spec{w}, toNatInt_extract30]
  exact bool_to_bits_of _ _ (af_sub_gen _ _ (by omega) (by omega))

theorem adc_af_spec{w}_eq (x y : BitVec {w}) (c : Bool) :
    adc_af_spec{w} x y (BitVec.ofBool c) = BitVec.ofBool (decide (x.toNat % 16 + y.toNat % 16 + c.toNat > 15)) := by
  simp only [adc_af_spec{w}, toNatInt_extract30]
  have : Sail.BitVec.toNatInt (BitVec.ofBool c) = ((c.toNat : Nat) : Int) := by cases c <;> rfl
  rw [this]
  exact bool_to_bits_of _ _ (af_adc_gen _ _ _ (by omega) (by omega) (by cases c <;> decide))

theorem sbb_af_spec{w}_eq (x y : BitVec {w}) (c : Bool) :
    sbb_af_spec{w} x y (BitVec.ofBool c) = BitVec.ofBool (decide (x.toNat % 16 < y.toNat % 16 + c.toNat)) := by
  simp only [sbb_af_spec{w}, toNatInt_extract30]
  have : Sail.BitVec.toNatInt (Sail.BitVec.zeroExtend (BitVec.ofBool c) 4) = ((c.toNat : Nat) : Int) := by
    cases c <;> rfl
  rw [this]
  exact bool_to_bits_of _ _ (af_sbb_gen _ _ _)

end JanusX86.Proofs
namespace JanusX86.Proofs
open X86Sail X86Sail.Functions
''')
P('\nend JanusX86.Proofs\n')
sys.stdout.write('\n'.join(out))
