package basic

// The functions below compare, hash and copy values through the runtime's equality, hashing
// and typed-memory functions (runtime/alg.go, runtime/mbarrier.go); the proofs treat those as
// contracts or execute them (docs/RUNTIME-CONTRACTS.md, "Equality, hashing and typed memory").

// Eq32 compares two 32-byte arrays.
//
//go:noinline
func Eq32(a, b *[32]byte) bool { return *a == *b }

// StrEq compares two strings.
//
//go:noinline
func StrEq(s, t string) bool { return s == t }

// F64Eq compares two float64 values (IEEE: NaN is unequal to everything, +0 == -0).
//
//go:noinline
func F64Eq(x, y float64) bool { return x == y }

// Tree is a struct with pointers.
type Tree struct {
	Next *Tree
	Name string
	Val  uint64
	Kids [4]*Tree
}

// CopyNode copies *src to *dst.
//
//go:noinline
func CopyNode(dst, src *Tree) { *dst = *src }

// CopyTrees copies the array *src to *dst. The arrays may overlap partially (through slice to
// array-pointer conversions), so the compiler copies them with runtime.typedmemmove.
//
//go:noinline
func CopyTrees(dst, src *[2]Tree) { *dst = *src }

// ClearTrees zeroes the elements of s (runtime.memclrHasPointers).
//
//go:noinline
func ClearTrees(s []*Tree) { clear(s) }

// LookupStr returns m[k] and whether k is present.
//
//go:noinline
func LookupStr(m map[string]uint64, k string) (uint64, bool) {
	v, ok := m[k]
	return v, ok
}

// FKey is a map key with a float, whose hash is generated by the compiler.
type FKey struct {
	F float64
	S string
}

// LookupFKey returns m[k].
//
//go:noinline
func LookupFKey(m map[FKey]uint64, k FKey) uint64 { return m[k] }
