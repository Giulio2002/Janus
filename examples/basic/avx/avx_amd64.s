#include "textflag.h"

// func indexByte64(p *[64]byte, c byte) int
TEXT ·indexByte64(SB), NOSPLIT, $0-24
	MOVQ	p+0(FP), SI
	MOVBLZX	c+8(FP), AX
	VMOVD	AX, X0
	VPBROADCASTB	X0, Y0
	VPCMPEQB	(SI), Y0, Y1
	VPCMPEQB	32(SI), Y0, Y2
	VPMOVMSKB	Y1, AX
	VPMOVMSKB	Y2, BX
	SHLQ	$32, BX
	ORQ	BX, AX
	TZCNTQ	AX, AX
	VZEROUPPER
	MOVQ	AX, ret+16(FP)
	RET

// func maxU32x8(p *[8]uint32) uint32
TEXT ·maxU32x8(SB), NOSPLIT, $0-12
	MOVQ	p+0(FP), SI
	VMOVDQU	(SI), Y0
	VEXTRACTI128	$1, Y0, X1
	VPMAXUD	X1, X0, X0
	VPSHUFD	$0x4E, X0, X1
	VPMAXUD	X1, X0, X0
	VPSHUFD	$0xB1, X0, X1
	VPMAXUD	X1, X0, X0
	VMOVD	X0, AX
	VZEROUPPER
	MOVL	AX, ret+8(FP)
	RET
