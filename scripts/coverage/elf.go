package main

// Function enumeration and instruction sweeps over Go executables and C object files.
//
// This code only chooses what to feed the trusted Lean decoders (janus-decode, janus-oracle-amd64);
// the accept/reject verdict of every instruction is the Lean model's.

import (
	"debug/elf"
	"debug/gosym"
	"encoding/binary"
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/Giulio2002/Janus/oracle-amd64/gen"
	"golang.org/x/arch/x86/x86asm"
)

// Kind of a function, from the pclntab file of its entry PC (Go binaries) or "c" (C objects).
const (
	KindGo      = "go"      // Go-compiled, non-test source
	KindTest    = "test"    // Go-compiled from a _test.go file or the generated test main
	KindAsm     = "asm"     // hand-written Go assembly (.s)
	KindWrapper = "wrapper" // <autogenerated>: ABI wrappers, method wrappers, equality functions
	KindC       = "c"
)

type Func struct {
	Name  string
	Pkg   string // std package directory (Go), or the C object's base name
	File  string
	Kind  string
	Addr  uint64
	Insts [][]byte // arm64: 4-byte words; amd64: one swept instruction each
	Calls []uint64 // direct call / tail-branch targets outside the function
}

type Image struct {
	Path  string
	Arch  string // arm64 | amd64
	Funcs []*Func
	byAdr map[uint64]*Func
}

func archOf(f *elf.File) (string, error) {
	switch f.Machine {
	case elf.EM_AARCH64:
		return "arm64", nil
	case elf.EM_X86_64:
		return "amd64", nil
	}
	return "", fmt.Errorf("unsupported machine %v", f.Machine)
}

// pkgOfFile maps a -trimpath pclntab file name to its std package directory.
func pkgOfFile(file string) string {
	if file == "" || strings.HasPrefix(file, "<") {
		return ""
	}
	file = strings.TrimPrefix(file, "$GOROOT/src/")
	if i := strings.Index(file, "/src/"); i >= 0 && strings.Contains(file[:i], "go") {
		file = file[i+5:]
	}
	return path.Dir(file)
}

// pkgOfSym guesses the package of a symbol from its name (for wrappers).
func pkgOfSym(name string) string {
	n := name
	if i := strings.IndexAny(n, "[("); i >= 0 {
		n = n[:i]
	}
	slash := strings.LastIndex(n, "/")
	if j := strings.Index(n[slash+1:], "."); j >= 0 {
		return n[:slash+1+j]
	}
	return n
}

func loadImage(p string) (*Image, error) {
	f, err := elf.Open(p)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	arch, err := archOf(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %v", p, err)
	}
	img := &Image{Path: p, Arch: arch, byAdr: map[uint64]*Func{}}
	var tab *gosym.Table
	text := f.Section(".text")
	if pcln := f.Section(".gopclntab"); pcln != nil && text != nil {
		pd, _ := pcln.Data()
		tab, _ = gosym.NewTable(nil, gosym.NewLineTable(pd, text.Addr))
	}
	isObj := f.Type == elf.ET_REL
	syms, err := f.Symbols()
	if err != nil {
		return nil, fmt.Errorf("%s: %v", p, err)
	}
	type rng struct {
		name   string
		sec    int
		lo, hi uint64
	}
	bySec := map[int][]rng{}
	for _, s := range syms {
		if elf.ST_TYPE(s.Info) != elf.STT_FUNC || s.Section == elf.SHN_UNDEF || int(s.Section) >= len(f.Sections) {
			continue
		}
		sec := f.Sections[s.Section]
		if sec.Flags&elf.SHF_EXECINSTR == 0 {
			continue
		}
		bySec[int(s.Section)] = append(bySec[int(s.Section)], rng{s.Name, int(s.Section), s.Value, s.Value + s.Size})
	}
	for si, fns := range bySec {
		sec := f.Sections[si]
		data, err := sec.Data()
		if err != nil {
			return nil, fmt.Errorf("%s: %v", p, err)
		}
		base := sec.Addr
		if isObj {
			base = 0
		}
		sort.Slice(fns, func(i, j int) bool { return fns[i].lo < fns[j].lo })
		end := base + uint64(len(data))
		for i, fn := range fns {
			if i > 0 && fns[i-1].lo == fn.lo {
				continue // alias
			}
			hi := fn.hi
			if hi == fn.lo {
				hi = end
				if i+1 < len(fns) {
					hi = fns[i+1].lo
				}
			}
			hi = min(hi, end)
			if fn.lo < base || fn.lo >= hi {
				continue
			}
			fu := &Func{Name: fn.name, Addr: fn.lo, Kind: KindC, Pkg: strings.TrimSuffix(path.Base(p), ".o")}
			if !isObj {
				fu.Kind = KindGo
				if tab != nil {
					// A Go function starts at a pclntab entry. The external linker's host
					// objects (the C code of a cgo binary, the C runtime) are covered by pclntab
					// entries with no file; their functions are the ELF symbols inside them.
					gf := tab.PCToFunc(fn.lo)
					if gf == nil {
						continue // not a function (runtime.etext and other markers)
					}
					file, _, _ := tab.PCToLine(fn.lo)
					if file != "" && gf.Entry != fn.lo {
						continue
					}
					if file == "" && fn.name == gf.Name && strings.Contains(gf.Name, "(.text") {
						continue // the host object's pseudo-function; its symbols are measured instead
					}
					fu.File = file
					fu.Pkg = pkgOfFile(file)
					switch {
					case file == "":
						// host objects of an externally linked cgo binary: its C code and the C runtime
						fu.Kind = KindC
						fu.Pkg = "(C in " + strings.TrimSuffix(path.Base(p), ".test") + ")"
					case strings.HasSuffix(file, ".s"):
						fu.Kind = KindAsm
					case strings.HasPrefix(file, "<"):
						fu.Kind = KindWrapper
					case strings.HasSuffix(file, "_test.go") || strings.HasSuffix(file, "_testmain.go") || strings.Contains(file, "_testmain"):
						fu.Kind = KindTest
					}
				}
				if fu.Pkg == "" || fu.Pkg == "." {
					fu.Pkg = pkgOfSym(strings.TrimSuffix(fn.name, ".abi0"))
				}
			}
			b := data[fn.lo-base : hi-base]
			if arch == "arm64" {
				sweepArm64(fu, b)
			} else {
				sweepAmd64(fu, b)
			}
			if len(fu.Insts) == 0 {
				continue
			}
			img.Funcs = append(img.Funcs, fu)
			img.byAdr[fu.Addr] = fu
		}
	}
	sort.Slice(img.Funcs, func(i, j int) bool { return img.Funcs[i].Addr < img.Funcs[j].Addr })
	return img, nil
}

func sweepArm64(fu *Func, b []byte) {
	n := len(b) / 4
	// Trailing zero words are the linker's `udf #0` padding (janus extract trims them too).
	for n > 0 && binary.LittleEndian.Uint32(b[4*(n-1):]) == 0 {
		n--
	}
	lo, hi := fu.Addr, fu.Addr+uint64(4*n)
	// Literal pools: the Go arm64 assembler places the constants of `LDR (literal)` after the
	// code of the function. Those words are data, never executed; leave them out.
	data := map[int]bool{}
	for i := 0; i < n; i++ {
		x := binary.LittleEndian.Uint32(b[4*i:])
		if x&0x3B000000 == 0x18000000 { // LDR/LDRSW (literal), GPR or SIMD&FP
			off := int64(int32(x<<8)) >> 11 // imm19 * 4
			j := i + int(off/4)
			size := 1
			switch x >> 30 {
			case 1:
				size = 2 // 64-bit (or D)
			case 2:
				if x&0x04000000 != 0 {
					size = 4 // Q
				} else {
					size = 1 // LDRSW
				}
			}
			if j > i && j < n {
				for k := 0; k < size && j+k < n; k++ {
					data[j+k] = true
				}
			}
		}
	}
	for i := 0; i < n; i++ {
		if data[i] {
			continue
		}
		w := b[4*i : 4*i+4]
		fu.Insts = append(fu.Insts, w)
		x := binary.LittleEndian.Uint32(w)
		pc := fu.Addr + uint64(4*i)
		if x&0x7C000000 == 0x14000000 { // B / BL imm26
			off := int64(int32(x<<6)) >> 4
			t := uint64(int64(pc) + off)
			if t < lo || t >= hi {
				fu.Calls = append(fu.Calls, t)
			}
		}
	}
}

// vexLen computes the length of a VEX (C4/C5) or EVEX (62) encoded instruction at b, for
// encodings x86asm does not know (it has no EVEX at all), so that the sweep stays in sync.
func vexLen(b []byte) int {
	if len(b) < 3 {
		return 0
	}
	var mp, n int
	switch b[0] {
	case 0xC5:
		mp, n = 1, 2
	case 0xC4:
		mp, n = int(b[1]&0x1F), 3
	case 0x62:
		if len(b) < 4 {
			return 0
		}
		mp, n = int(b[1]&0x07), 4
	default:
		return 0
	}
	if len(b) < n+2 {
		return 0
	}
	op := b[n]
	modrm := b[n+1]
	l := n + 2
	mod, rm := modrm>>6, modrm&7
	if mod != 3 {
		if rm == 4 {
			if len(b) <= l {
				return 0
			}
			sib := b[l]
			l++
			if mod == 0 && sib&7 == 5 {
				l += 4
			}
		}
		switch mod {
		case 0:
			if rm == 5 {
				l += 4
			}
		case 1:
			l++
		case 2:
			l += 4
		}
	}
	switch {
	case mp == 3:
		l++
	case mp == 1 && (op >= 0x70 && op <= 0x73 || op == 0xC2 || op == 0xC4 || op == 0xC5 || op == 0xC6):
		l++
	}
	if l > len(b) || l > 15 {
		return 0
	}
	return l
}

// modrmLen is the length of a ModRM byte and its SIB/displacement at b[0] (64-bit addressing).
func modrmLen(b []byte) int {
	if len(b) == 0 {
		return 0
	}
	modrm := b[0]
	l := 1
	mod, rm := modrm>>6, modrm&7
	if mod != 3 {
		if rm == 4 {
			if len(b) <= l {
				return 0
			}
			sib := b[l]
			l++
			if mod == 0 && sib&7 == 5 {
				l += 4
			}
		}
		switch mod {
		case 0:
			if rm == 5 {
				l += 4
			}
		case 1:
			l++
		case 2:
			l += 4
		}
	}
	return l
}

// legacyLen computes the length of a legacy 0F 38 / 0F 3A instruction x86asm does not know
// (ADCX/ADOX, newer SSE forms), so that the sweep stays in sync.
func legacyLen(b []byte) int {
	q := legacyPrefixEnd(b)
	if q < len(b) && b[q] >= 0x40 && b[q] <= 0x4F {
		q++
	}
	if q+3 > len(b) || b[q] != 0x0F || (b[q+1] != 0x38 && b[q+1] != 0x3A) {
		return 0
	}
	m := modrmLen(b[q+3:])
	if m == 0 {
		return 0
	}
	l := q + 3 + m
	if b[q+1] == 0x3A {
		l++
	}
	if l > len(b) || l > 15 {
		return 0
	}
	return l
}

func legacyPrefixEnd(b []byte) int {
	i := 0
	for i < len(b) {
		switch c := b[i]; {
		case c == 0x66 || c == 0x67 || c == 0xF2 || c == 0xF3 || c == 0x2E || c == 0x3E || c == 0x26 || c == 0x36 || c == 0x64 || c == 0x65 || c == 0xF0:
			i++
		default:
			return i
		}
	}
	return i
}

func sweepAmd64(fu *Func, b []byte) {
	// INT3 (0xCC) padding is skipped at instruction boundaries only (a trailing JMP rel8 can
	// end in a 0xCC displacement byte).
	lo, hi := fu.Addr, fu.Addr+uint64(len(b))
	for p := 0; p < len(b); {
		if b[p] == 0xCC {
			p++
			continue
		}
		win := b[p:min(len(b), p+15)]
		inst, ok := gen.Decode(win)
		l := 0
		if len(win) >= 4 && win[0] == 0xF3 && win[1] == 0x0F && win[2] == 0x1E && (win[3] == 0xFA || win[3] == 0xFB) {
			l, ok = 4, false // ENDBR64/ENDBR32 (CET), unknown to x86asm
		} else if ok && inst.Len > 0 {
			l = inst.Len
		} else {
			q := legacyPrefixEnd(win)
			if q < len(win) {
				if v := vexLen(win[q:]); v > 0 {
					l = q + v
				} else if v := legacyLen(win); v > 0 {
					l = v
				}
			}
			if l == 0 {
				l = 1
			}
		}
		fu.Insts = append(fu.Insts, b[p:p+l])
		if ok && (inst.Op == x86asm.CALL || inst.Op == x86asm.JMP) && len(inst.Args) > 0 {
			if rel, isRel := inst.Args[0].(x86asm.Rel); isRel {
				t := uint64(int64(fu.Addr) + int64(p+l) + int64(rel))
				if t < lo || t >= hi {
					fu.Calls = append(fu.Calls, t)
				}
			}
		}
		p += l
	}
}
