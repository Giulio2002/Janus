#!/usr/bin/env bash
# Lint: no hard-coded code or data addresses in the example proofs (examples/**/*.lean).
#
# A numeric literal (decimal or 0x hex) that falls inside a loaded section (SHF_ALLOC: text, rodata, data, bss) of the
# example binaries is the shape of an address inside them. The ranges are READ FROM THE ELF SECTION HEADERS of every
# artifacts/examples-* binary that exists (amd64 images are linked at 0x400000, arm64 ones at 0x10000); with no binary
# built yet (the gate runs this lane before the builds) the static fallback below is used (amd64 [0x400f00, 0x5b0000),
# arm64 [0x10f00, 0x1b8000), just above the ELF headers). `--ranges` prints the ranges in use. A literal is ignored when it is < 0x10000, a multiple
# of 0x1000 (a page-aligned window or heap: 0x500000, 4194304, 0x11000), a decimal multiple of 1000 (a size: 8000000) or
# 2^k - 1 (a mask or bound: 2097151). It silently goes
# stale when the binary's layout moves (any example added to the shared binary shifts code by 32/64 bytes and data by
# 128), so a proof must take it from the extraction instead: `janus_eval% (Extracted.entry + k)`, `segAddr
# Extracted.program "<symbol>"`, `Extracted.dataAddr.«<name>»`, `ripTarget Extracted.program (Extracted.entry + k)`.
# Those round numbers are synthetic choices of the proof (a heap, a window, a size), not addresses of the binary. A genuine non-round constant is allowed with the comment
# `-- addr-ok: <why>` on the same line or on the line above. Comments are not scanned; generated files ("Generated by" in
# the first lines: extraction listings) are skipped.
#
#   scripts/lint-example-addresses.sh [DIR...]     (default: examples)      exit 1 and a list when there are hits
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
[ "$#" -gt 0 ] && [ "${1:-}" != "--ranges" ] || set -- examples "$@"
exec python3 -I - "$@" <<'PY'
import os, re, sys
import glob, struct
STATIC = [(0x400f00, 0x5b0000), (0x10f00, 0x1b8000)]
def elf_ranges(path):
    try:
        with open(path, 'rb') as f:
            h = f.read(64)
            if h[:4] != b'\x7fELF' or h[4] != 2 or h[5] != 1:
                return []
            shoff, = struct.unpack_from('<Q', h, 0x28)
            shentsize, shnum = struct.unpack_from('<HH', h, 0x3a)
            f.seek(shoff)
            tab = f.read(shentsize * shnum)
    except OSError:
        return []
    out = []
    for i in range(shnum):
        flags, addr = struct.unpack_from('<QQ', tab, i * shentsize + 8)
        size, = struct.unpack_from('<Q', tab, i * shentsize + 32)
        if flags & 2 and addr and size:   # SHF_ALLOC
            out.append((addr, addr + size))
    if not out:
        return out
    lo = min(a for a, _ in out)
    # a sparse bss (the C runtime's arenas) is not a place proofs name: keep the first 4 MiB of the image
    return [(a, min(b, lo + 0x400000)) for a, b in out if a < lo + 0x400000]
def build_ranges():
    rs = []
    for p in sorted(glob.glob('artifacts/examples-*')):
        if os.path.isfile(p):
            rs += elf_ranges(p)
    if not rs:
        return STATIC, 'static fallback (no artifacts/examples-* binary built)'
    rs.sort()
    merged = [list(rs[0])]
    for a, b in rs[1:]:
        if a <= merged[-1][1] + 0x1000:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return [tuple(x) for x in merged], 'ELF section headers of artifacts/examples-*'
RANGES, SRC = build_ranges()
if os.environ.get('LINT_ADDR_SHOW_RANGES') or '--ranges' in sys.argv:
    print('lint-example-addresses ranges (%s):' % SRC)
    for a, b in RANGES:
        print('  [0x%x, 0x%x)' % (a, b))
    if '--ranges' in sys.argv:
        sys.exit(0)
def in_range(v):
    return any(a <= v < b for a, b in RANGES)
lit = re.compile(r'(?<![\w.#])(0x[0-9a-fA-F_]+|[0-9][0-9_]*)(?![\w.])')
bad = []
files = 0
for top in [a for a in sys.argv[1:] if a != '--ranges']:
    for root, ds, fs in os.walk(top):
        ds[:] = sorted(d for d in ds if not d.startswith('.'))   # scratch copies (.print-proofs.XXXX)
        for f in sorted(fs):
            if not f.endswith('.lean'):
                continue
            p = os.path.join(root, f)
            files += 1
            head = ''.join(open(p, encoding='utf-8', errors='replace').readlines()[:12])
            if re.search(r'[Gg]enerated by', head):
                continue   # an extraction listing (Extracted.lean, gen-print-code.py output): it IS the layout
            prev = ''
            in_block = 0
            for n, line in enumerate(open(p, encoding='utf-8', errors='replace'), 1):
                raw = line.rstrip('\n')
                code = raw
                # strip block comments (nesting not needed for this tree) and line comments
                out = ''
                i = 0
                while i < len(code):
                    if in_block:
                        j = code.find('-/', i)
                        if j < 0:
                            i = len(code)
                        else:
                            in_block = 0
                            i = j + 2
                        continue
                    if code.startswith('/-', i):
                        in_block = 1
                        i += 2
                        continue
                    if code.startswith('--', i):
                        break
                    out += code[i]
                    i += 1
                allowed = 'addr-ok' in raw or 'addr-ok' in prev
                for m in lit.finditer(out):
                    t = m.group(1).replace('_', '')
                    try:
                        v = int(t, 16) if t.startswith('0x') else int(t)
                    except ValueError:
                        continue
                    dec_round = not t.startswith('0x') and v % 1000 == 0
                    # synthetic values: a size (decimal multiple of 1000), a window or heap (page aligned), a mask or
                    # bound (2^k - 1)
                    synthetic = dec_round or v % 0x1000 == 0 or (v + 1) & v == 0
                    if v >= 0x10000 and not synthetic and in_range(v) and not allowed:
                        bad.append((p, n, t))
                prev = raw
if bad:
    print('lint-example-addresses: %d hard-coded address literal(s) in the example proofs:' % len(bad), file=sys.stderr)
    for p, n, t in bad:
        print('  %s:%d: %s' % (p, n, t), file=sys.stderr)
    print('Take the address from the extraction (janus_eval% (Extracted.entry + k), segAddr Extracted.program "sym",', file=sys.stderr)
    print('Extracted.dataAddr.«name»), or mark a genuine constant with `-- addr-ok: <why>`.', file=sys.stderr)
    sys.exit(1)
print('lint-example-addresses: %d example files, no hard-coded binary addresses' % files)
PY
