#!/usr/bin/env python3
"""Generate examples/proofs-print/PrintProofs/<Isa>/Code.lean: the code of the print examples
(every function their four entry points reach, as `janus extract` copies it from the binary) as one
`Program`, `PrintCode.program`, that the per-function proof modules (PrintProofs.<Isa>.Fn*) are
about. Those modules do not import `Extracted` (so they are built once and shared by the four
examples); each example module proves `PrintCode.program` and its own `Extracted.program` have the
same code (`Program.Equiv`, by `decide`) and transports the result.

Usage: scripts/gen-print-code.py [--check] ISA...   (default: both ISAs)
Needs bin/janus and artifacts/examples-print-<isa> (scripts/build-examples-print.sh). The code is
the extraction of PrintX with the other entry points as --targets; --check fails if the checked-in
file differs from it."""
import os, re, subprocess, sys, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["PrintX", "PrintBool", "PrintNeg", "PrintStr"]
def extract(isa, n, out):
    others = ",".join("example.com/print." + m for m in NAMES if m != n)
    subprocess.run([os.path.join(root, "bin", "janus"), "extract", os.path.join(root, "artifacts", "examples-print-" + isa),
                    "example.com/print." + n, out, "--targets", others, "--contract", "runtime.lock2",
                    "--contract", "runtime.unlock2", "--contract", "runtime.memmove"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, cwd=root)
def code(isa):
    with tempfile.TemporaryDirectory() as tmp:
        entries = {}
        text = None
        for n in NAMES:
            out = os.path.join(tmp, n)
            extract(isa, n, out)
            t = open(os.path.join(out, "Extracted.lean"), encoding="utf-8").read()
            entries[n] = re.search(r"^def entry : Nat := (0x[0-9a-f]+)$", t, re.M).group(1)
            if n == "PrintX":
                text = t
    ns = {"arm64": "Arm64", "amd64": "Amd64"}[isa]
    t = text
    t = re.sub(r"/-! Generated by.*?-/\n", "", t, count=1, flags=re.S)
    t = t.replace("import Janus\n", "import Janus\n", 1)
    head = ("/-! The code of the print examples (generated by `scripts/gen-print-code.py`; do not edit):\n"
            "the extraction of `example.com/print.PrintX` with the other three entry points as `--targets`, as one\n"
            "program. The per-function proofs (`PrintProofs.%s.Fn*`) are about it; each example proves it\n"
            "has the same code as its own `Extracted.program` (`Program.Equiv`). -/\n" % ns)
    t = t.replace("namespace Extracted", head + "\nnamespace PrintCode", 1)
    t = re.sub(r"\ndef entry : Nat := 0x[0-9a-f]+\n", "\n", t)
    ents = "".join("/-- The entry point of `example.com/print.%s`. -/\ndef entry%s : Nat := %s\n\n" % (n, n, entries[n]) for n in NAMES)
    t = t.replace("end Extracted", ents + "end PrintCode")
    return t
def main():
    check = "--check" in sys.argv[1:]
    isas = [a for a in sys.argv[1:] if not a.startswith("--")] or ["arm64", "amd64"]
    bad = 0
    for isa in isas:
        ns = {"arm64": "Arm64", "amd64": "Amd64"}[isa]
        path = os.path.join(root, "examples", "proofs-print", "PrintProofs", ns, "Code.lean")
        new = code(isa)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != new:
            if check:
                print("stale: %s (run scripts/gen-print-code.py)" % os.path.relpath(path, root)); bad = 1
            else:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(new); print("wrote", os.path.relpath(path, root))
    sys.exit(bad)
main()
