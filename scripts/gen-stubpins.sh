#!/usr/bin/env bash
# Generate cmd/janus/stubpins_gen.go: the code of every runtime stub Janus models as an outcome
# (and of the functions those stubs call), per architecture, as built by pinned Go toolchains.
# See cmd/janus/stubpin.go and docs/SOUNDNESS.md (stub classification).
#
# For every toolchain, architecture and build mode below it builds the example program
# (examples/basic/cmd), the round-7 assembly fixture (arm64), and scripts/stubpins (which links
# every listed stub), runs `janus stubpins` on each binary, and writes the union of the
# measured (name, file, normalized hash) triples. It also prints the stability table: for each
# architecture, how many names have exactly one hash over all binaries of a toolchain.
#
# Usage: scripts/gen-stubpins.sh [--check] [TOOLCHAIN...]
#   TOOLCHAIN defaults to $JANUS_STUBPIN_TOOLCHAINS or "go1.26.0 go1.26.5 go1.26.8 go1.26.10"
#   (go1.26.0 is the toolchain of scripts/build-examples*.sh). Adding a release: append it here
#   and rerun. --check regenerates into a temporary file and fails if it differs from the
#   committed one. JANUS_STUBPIN_RAW=FILE also saves the raw measurements
#   ("stub|helper arch name file hash toolchain mode program" lines). Writes only cmd/janus/stubpins_gen.go and scripts/stubpins/main.go (and a
#   mktemp directory it removes).
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
export PATH="/usr/local/go/bin:$PATH"
check=0
if [ "${1:-}" = "--check" ]; then check=1; shift; fi
if [ $# -gt 0 ]; then toolchains=("$@"); else
  read -r -a toolchains <<<"${JANUS_STUBPIN_TOOLCHAINS:-go1.26.0 go1.26.5 go1.26.8 go1.26.10}"; fi
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

# scripts/stubpins/main.go: pull every listed stub by //go:linkname so the linker keeps it.
names=$(grep -oE '"runtime\.[A-Za-z0-9_]+(\.abi0)?": true' cmd/janus/extract.go | cut -d'"' -f2 | grep -v '\.abi0$' | sort -u)
{
  cat <<'EOF'
// Command stubpins references every runtime stub on Janus's list (cmd/janus/extract.go), so
// that the linker keeps them all; scripts/gen-stubpins.sh measures their code in this binary
// (and in the example binaries) to generate cmd/janus/stubpins_gen.go. It is built with
// -ldflags=-checklinkname=0 (it pulls runtime functions by //go:linkname) and never run.
// Code generated by scripts/gen-stubpins.sh. DO NOT EDIT.
package main

import (
	"fmt"
	_ "unsafe" // for go:linkname
)

EOF
  for n in $names; do echo "//go:linkname s_${n#runtime.} $n"; echo "func s_${n#runtime.}()"; echo; done
  echo "var keep = []func(){"; for n in $names; do echo "	s_${n#runtime.},"; done; echo "}"
  echo; echo 'func main() { fmt.Println(len(keep)) }'
} >"$tmp/main.go"
if [ $check = 1 ]; then cmp -s "$tmp/main.go" scripts/stubpins/main.go || { echo "scripts/stubpins/main.go is stale"; exit 1; }
else cp "$tmp/main.go" scripts/stubpins/main.go; fi

go build -o "$tmp/janus" ./cmd/janus

# modes per architecture: NAME|ENV|FLAGS. PIE is measured (stability table) but not pinned:
# extraction rejects ET_DYN binaries, and on amd64 the linker rewrites TLS accesses in PIE code.
# (Stripped binaries, -ldflags=-s, have no ELF symbol table: classifyStub rejects them first.)
modes() {
  local common=("default||" "trimpath||-trimpath" "nodwarf||-trimpath -ldflags=-w" "pie||-trimpath -buildmode=pie"
                "noopt||-trimpath -gcflags=all=-N_-l")
  printf '%s\n' "${common[@]}"
  if [ "$1" = arm64 ]; then printf '%s\n' "v8.1|GOARM64=v8.1|-trimpath" "v9.0|GOARM64=v9.0|-trimpath"
  else printf '%s\n' "v2|GOAMD64=v2|-trimpath" "v3|GOAMD64=v3|-trimpath" "v4|GOAMD64=v4|-trimpath"; fi
}
: >"$tmp/all"
for tc in "${toolchains[@]}"; do
  for arch in arm64 amd64; do
    while IFS='|' read -r mode env flags; do
      progs=("examples/basic|./cmd" "scripts/stubpins|.")
      [ "$arch" = arm64 ] && progs+=("audit/round7/asmstub|./cmd")
      for pr in "${progs[@]}"; do
        dir=${pr%%|*}; pkg=${pr#*|}; bin="$tmp/bin-$tc-$arch-$mode-$(basename "$dir")"
        extra=()
        [ "$dir" = scripts/stubpins ] && extra=(-ldflags=-checklinkname=0)
        # -ldflags given twice: the last wins, so merge -w into the linkname flag
        fl=(${flags//-ldflags=-w/})
        if [[ $flags == *-ldflags=-w* ]]; then
          if [ ${#extra[@]} -gt 0 ]; then extra=(-ldflags="-w -checklinkname=0"); else extra=(-ldflags=-w); fi
        fi
        fl=("${fl[@]//-N_-l/-N -l}")
        ( cd "$dir" && env GOTOOLCHAIN="$tc" CGO_ENABLED=0 GOOS=linux GOARCH="$arch" GOFLAGS=-mod=mod $env \
            go build -buildvcs=false "${fl[@]}" "${extra[@]}" -o "$bin" "$pkg" ) >"$tmp/build.log" 2>&1 ||
          { echo "build failed: $tc $arch $mode $dir"; cat "$tmp/build.log"; exit 1; }
        "$tmp/janus" stubpins "$bin" | sed "s|\$| $tc $mode $(basename "$dir")|" >>"$tmp/all"
        rm -f "$bin"
      done
    done < <(modes "$arch")
  done
done

[ -n "${JANUS_STUBPIN_RAW:-}" ] && cp "$tmp/all" "$JANUS_STUBPIN_RAW"
# Stability. Within one toolchain, architecture and build mode, every program must give a name
# the same normalized hash (otherwise the normalization is too weak: fail). Across modes, list
# the names whose code differs (a genuinely different compilation of the runtime).
unstable=$(awk '{k=$6" "$2" "$7" "$3; if (!((k,$5) in s)) {s[k,$5]=1; n[k]++}} END {for (k in n) if (n[k]>1) print "  " k " (" n[k] " hashes)"}' "$tmp/all" | sort)
if [ -n "$unstable" ]; then echo "UNSTABLE across programs within a build mode:"; echo "$unstable"; exit 1; fi
echo "stable across programs within every toolchain/arch/mode ($(awk '{print $8}' "$tmp/all" | sort -u | tr '\n' ' '))"
echo "names per toolchain/arch, and the modes whose code differs from the default build:"
awk '{t=$6" "$2; nm[t SUBSEP $3]=1; if ($7=="default") d[t SUBSEP $3]=$5; h[t SUBSEP $3 SUBSEP $7]=$5}
     END {for (x in nm) {split(x, a, SUBSEP); tot[a[1]]++}
          for (x in h) {split(x, a, SUBSEP); k=a[1] SUBSEP a[2]; if (h[x]!=d[k]) {v[a[1]]=v[a[1]] " " a[2] "[" a[3] "]"; diff[k]=1}}
          for (k in diff) {split(k, a, SUBSEP); nd[a[1]]++}
          for (t in tot) printf "  %-18s %3d names, %3d identical in every mode;%s\n", t, tot[t], tot[t]-nd[t], v[t]}' "$tmp/all" | sort

out="$tmp/stubpins_gen.go"
{
  echo "// Code generated by scripts/gen-stubpins.sh. DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "// stubPinToolchains are the toolchains whose runtime code stubPins records."
  echo "const stubPinToolchains = \"${toolchains[*]}\""
  echo
  echo "// stubPins: per GOARCH and linked name, the accepted (normalized SHA-256, GOROOT/src file)"
  echo "// pairs, each with the toolchains and build modes it was measured in (modes: default; trimpath;"
  echo "// nodwarf, -ldflags=-w; noopt, -gcflags=all=-N -l; v8.1/v9.0, GOARM64; v2/v3/v4, GOAMD64)."
  echo "var stubPins = map[string]map[string][]stubPin{"
  for arch in amd64 arm64; do
    echo "	\"$arch\": {"
    awk -v A="$arch" '$2==A && $7!="pie" {key=$3" "$4" "$5; if (!(key SUBSEP $6 SUBSEP $7 in s)) {s[key SUBSEP $6 SUBSEP $7]=1; tag[key]=tag[key]" "$6"/"$7}} END {for (k in tag) print k" |"tag[k]}' "$tmp/all" |
      sort | awk '{name=$1; if (name!=prev) {if (prev!="") print "\t\t},"; printf "\t\t\"%s\": {\n", name; prev=name}
                   tags=$0; sub(/^[^|]*\| /, "", tags); n=split(tags, t, " "); delete tc; delete md; lst=""; mds=""
                   for (i=1;i<=n;i++) {split(t[i], p, "/"); if (!(p[1] in tc)) {tc[p[1]]=1; lst=lst (lst==""?"":" ") p[1]}
                                       if (!(p[2] in md)) {md[p[2]]=1; mds=mds (mds==""?"":" ") p[2]}}
                   printf "\t\t\t{Hash: \"%s\", File: \"%s\"}, // %s: %s\n", $3, $2, lst, mds}
                   END {if (prev!="") print "\t\t},"}'
    echo "	},"
  done
  echo "}"
  echo
  echo "// stubPinHelpers are the functions the non-terminal stubs call (also pinned in stubPins)."
  echo "var stubPinHelpers = map[string]bool{"
  awk '$1=="helper" && $7!="pie" {print $3}' "$tmp/all" | sort -u | sed 's/.*/	"&": true,/'
  echo "}"
} >"$out"
gofmt -w "$out"
if [ $check = 1 ]; then
  if cmp -s "$out" cmd/janus/stubpins_gen.go; then echo "cmd/janus/stubpins_gen.go is up to date"
  else diff -u cmd/janus/stubpins_gen.go "$out" | head -40; echo "cmd/janus/stubpins_gen.go is stale"; exit 1; fi
else cp "$out" cmd/janus/stubpins_gen.go; echo "wrote cmd/janus/stubpins_gen.go"; fi
