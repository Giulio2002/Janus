#!/usr/bin/env python3
"""Assemble the amd64 witness stub of fmt.errorf for the format "%w: have %d, want %d bytes" and print a Lean
fragment (`def code64 : List Nat` and label addresses, base 0x100000). Run from the repo root:
  python3 scripts/errorf/gen_amd64.py > Janus/Contracts/ErrorfRealCode64.lean"""
import subprocess, sys, tempfile
IERR = 0x2222; IWRAP = 0x4444
def number(v, ends, lbl, outlen, outstart):
    return [f"mov rax, {v}", f"mov rdx, {v}", "neg rdx", f"test {v}, {v}", "cmovs rax, rdx",
            "xor edi, edi", f"test {v}, {v}", "sets dil",
            f"lea r13, [rsp-{ends}]", "mov ecx, 10",
            f"{lbl}d:", "xor edx, edx", "div rcx", "add edx, 48", "dec r13", "mov [r13], dl", "test rax, rax", f"jnz {lbl}d",
            f"{lbl}s:", "lea edx, [rdi+rdi*2]", "mov eax, 48", "sub eax, edx", "mov [r13-1], al", "sub r13, rdi",
            f"lea rdx, [rsp-{ends}]", f"sub rdx, r13", f"mov {outlen}, rdx", f"mov {outstart}, r13"]
def lit(bs):
    return [f"mov byte ptr [r11+{i}], {c}" for i, c in enumerate(bs)] + [f"add r11, {len(bs)}"]
def copy(lbl, src, cnt):
    return [f"mov rdi, {src}", f"mov r12, {cnt}", f"{lbl}:", "test r12, r12", f"jz {lbl}e", "mov al, [rdi]", "inc rdi",
            "mov [r11], al", "inc r11", "dec r12", f"jmp {lbl}", f"{lbl}e:"]
def prog():
    a = ["mov r8, [rcx+8]", "mov r9, [r8]", "mov r10, [r8+8]", "mov r11, [rcx+24]", "mov r11, [r11]",
         "mov r12, [rcx+40]", "mov r12, [r12]"]
    a += number("r11", 16, "n1", "rbx", "rsi")
    a += number("r12", 48, "n2", "r15", "r13")
    a += ["lea rax, [r10+rbx+20]", "add rax, r15", "mov r12, rax", "lea rax, [rax+rax+63]", "xor edx, edx", "mov ecx, 16",
          "div rcx", "imul rax, rax, 16", "mov edx, 0x400000", "mov rcx, [rdx]", "add rax, rcx", "mov [rdx], rax",
          "lea r11, [rcx+32]", "mov [rcx], r11", "mov [rcx+8], r12", f"mov qword ptr [rcx+16], {IERR}", "mov [rcx+24], r8",
          "mov r8, rcx"]
    a += copy("c1", "r9", "r10")
    a += lit([58, 32, 104, 97, 118, 101, 32])
    a += copy("c2", "rsi", "rbx")
    a += lit([44, 32, 119, 97, 110, 116, 32])
    a += copy("c3", "r13", "r15")
    a += lit([32, 98, 121, 116, 101, 115])
    a += [f"mov eax, {IWRAP}", "mov rbx, r8", "ret"]
    return a
def build():
    asm = prog()
    src = ".intel_syntax noprefix\n.text\n" + "\n".join(asm) + "\n"
    labels = {}
    with tempfile.TemporaryDirectory() as d:
        open(d + "/a.s", "w").write(src)
        subprocess.check_call(["as", "-o", d + "/a.o", d + "/a.s"])
        subprocess.check_call(["objcopy", "-O", "binary", "-j", ".text", d + "/a.o", d + "/a.bin"])
        nm = subprocess.check_output(["nm", d + "/a.o"]).decode().split("\n")
        b = open(d + "/a.bin", "rb").read()
    for l in nm:
        t = l.split()
        if len(t) == 3: labels[t[2]] = int(t[0], 16)
    return list(b), labels
if __name__ == "__main__":
    words, labels = build()
    print("/- GENERATED by scripts/errorf/gen_amd64.py. Do not edit. -/")
    print("namespace Janus.Contracts.ErrorfRealCode64\n")
    print("def code64 : List Nat := [" + ", ".join(hex(x) for x in words) + "]\n")
    for k, v in sorted(labels.items(), key=lambda x: x[1]):
        print(f"def pc_{k} : Nat := 0x100000 + {v}")
    print("\nend Janus.Contracts.ErrorfRealCode64")
    print(len(words), "bytes", file=sys.stderr)
