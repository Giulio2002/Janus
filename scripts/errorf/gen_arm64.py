#!/usr/bin/env python3
"""Assemble the arm64 witness stub of fmt.errorf for the format "%w: have %d, want %d bytes" and print a Lean
fragment: `def code : List Nat` and the word offsets of its labels. Run from the repo root:
  python3 scripts/errorf/gen_arm64.py > Janus/Contracts/ErrorfRealCode.lean   (the generated file is checked in)"""
import subprocess, sys, tempfile
IERR = 0x2222; IWRAP = 0x4444
def number(v, ends, lbl, outlen, outstart):
    return [f"cmp {v}, #0", f"cneg x11, {v}, lt", "cset x12, lt",
            f"sub x13, sp, #{ends}",
            f"{lbl}d:", "udiv x14, x11, x15", "msub x16, x14, x15, x11", "add x16, x16, #48",
            "strb w16, [x13, #-1]!", "mov x11, x14", f"cbnz x11, {lbl}d",
            f"{lbl}s:", "add x17, x12, x12, lsl #1", "mov x16, #48", "sub x16, x16, x17", "strb w16, [x13, #-1]",
            "sub x13, x13, x12",
            f"sub x17, sp, #{ends}", f"sub {outlen}, x17, x13", f"mov {outstart}, x13"]
def lit(bs):
    return [x for c in bs for x in (f"mov w16, #{c}", "strb w16, [x11], #1")]
def copy(lbl, src, cnt):
    return [f"mov x10, {src}", f"mov x12, {cnt}", f"{lbl}:", f"cbz x12, {lbl}e", "ldrb w16, [x10], #1",
            "strb w16, [x11], #1", "sub x12, x12, #1", f"b {lbl}", f"{lbl}e:"]
def prog():
    a = ["mov x15, #10", "ldr x5, [x2, #8]", "ldr x6, [x5]", "ldr x7, [x5, #8]", "ldr x8, [x2, #24]", "ldr x8, [x8]",
         "ldr x9, [x2, #40]", "ldr x9, [x9]"]
    a += number("x8", 16, "n1", "x25", "x26")
    a += number("x9", 48, "n2", "x21", "x22")
    a += ["add x3, x7, x21", "add x3, x3, x25", "add x3, x3, #20", "add x4, x3, x3", "add x4, x4, #63",
          "mov x14, #16", "udiv x4, x4, x14", "mul x4, x4, x14", "movz x0, #0x40, lsl #16", "ldr x1, [x0]", "add x4, x1, x4", "str x4, [x0]",
          "add x2, x1, #32", "str x2, [x1]", "str x3, [x1, #8]", f"movz x17, #{IERR}", "str x17, [x1, #16]", "str x5, [x1, #24]"]
    a += ["mov x11, x2"]
    a += copy("c1", "x6", "x7")
    a += lit([58, 32, 104, 97, 118, 101, 32])
    a += copy("c2", "x26", "x25")
    a += lit([44, 32, 119, 97, 110, 116, 32])
    a += copy("c3", "x22", "x21")
    a += lit([32, 98, 121, 116, 101, 115])
    a += [f"movz x0, #{IWRAP}", "ret"]
    return a
def build():
    asm = prog()
    src = ".text\n" + "\n".join(asm) + "\n"
    with tempfile.TemporaryDirectory() as d:
        open(d + "/a.s", "w").write(src)
        subprocess.check_call(["aarch64-linux-gnu-as", "-o", d + "/a.o", d + "/a.s"])
        subprocess.check_call(["aarch64-linux-gnu-objcopy", "-O", "binary", "-j", ".text", d + "/a.o", d + "/a.bin"])
        syms = subprocess.check_output(["aarch64-linux-gnu-nm", d + "/a.o"]).decode()
        b = open(d + "/a.bin", "rb").read()
    words = [int.from_bytes(b[i:i+4], "little") for i in range(0, len(b), 4)]
    labels = {}
    # local labels are not in nm; recompute by counting instructions
    idx = 0
    for l in asm:
        if l.endswith(":"):
            labels[l[:-1]] = idx
        else:
            idx += 1
    return words, labels
if __name__ == "__main__":
    words, labels = build()
    print("/- GENERATED by scripts/errorf/gen_arm64.py. Do not edit. -/")
    print("namespace Janus.Contracts.ErrorfRealCode\n")
    print("def code : List Nat := [" + ", ".join(hex(x) for x in words) + "]\n")
    for k, v in labels.items():
        print(f"def pc_{k} : Nat := 0x100000 + {4*v}")
    print("\nend Janus.Contracts.ErrorfRealCode")
    print(len(words), file=sys.stderr)
