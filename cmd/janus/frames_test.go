package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"testing"
)

// compilerFrames are the frame sizes the compiler reports (`go build -gcflags=-S`: "STEXT ...
// args=0xA locals=0xL"), an oracle independent of the pclntab reader.
func compilerFrames(t *testing.T, goarch string) map[string][2]uint64 {
	t.Helper()
	cmd := exec.Command("go", "build", "-gcflags=-S", "-o", os.DevNull, ".")
	cmd.Dir = filepath.Join(repoRoot, "examples", "basic")
	cmd.Env = append(os.Environ(), "GOOS=linux", "GOARCH="+goarch, "GOAMD64=v1", "CGO_ENABLED=0")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go build -S: %v\n%s", err, out)
	}
	re := regexp.MustCompile(`(?m)^(example\.com/basic\.\w+) STEXT .*args=0x([0-9a-f]+) locals=0x([0-9a-f]+)`)
	m := map[string][2]uint64{}
	for _, g := range re.FindAllStringSubmatch(string(out), -1) {
		a, _ := strconv.ParseUint(g[2], 16, 64)
		l, _ := strconv.ParseUint(g[3], 16, 64)
		m[g[1]] = [2]uint64{a, l}
	}
	return m
}

// The pclntab frame records (--frames) agree with the compiler's frame sizes, are recorded in
// identity.json and are regenerated by check.
func TestFramesRecords(t *testing.T) {
	for _, arch := range []string{"arm64", "amd64"} {
		t.Run(arch, func(t *testing.T) {
			bin := exampleBin
			if arch == "amd64" {
				bin = exampleAmd64(t)
			}
			want := compilerFrames(t, arch)
			for _, sym := range []string{"SumRec", "BigLocal", "HoldPtr"} {
				name := "example.com/basic." + sym
				dir := filepath.Join(t.TempDir(), "art")
				code, _, stderr := runJanus(t, "extract", bin, name, dir, "--frames")
				if code != 0 {
					t.Fatalf("extract %s --frames: %s", name, stderr)
				}
				if !readIdentity(t, dir).Frames {
					t.Fatalf("%s: identity.json does not record --frames", name)
				}
				lean, err := os.ReadFile(filepath.Join(dir, "Extracted.lean"))
				if err != nil {
					t.Fatal(err)
				}
				rec := regexp.MustCompile(`name := "([^"]+)", entry := 0x[0-9a-f]+, size := \d+, args := (\d+), funcID := \d+, flag := \d+, maxspd := (\d+)`)
				found := 0
				for _, g := range rec.FindAllStringSubmatch(string(lean), -1) {
					w, ok := want[g[1]]
					if !ok {
						continue
					}
					found++
					args, _ := strconv.ParseUint(g[2], 10, 64)
					maxspd, _ := strconv.ParseUint(g[3], 10, 64)
					wantSPD := w[1]
					if arch == "arm64" && w[1] > 0 {
						wantSPD += 8 // the saved link register at 0(SP)
					}
					if args != w[0] || maxspd != wantSPD {
						t.Errorf("%s %s: args %d maxspd %d, compiler says args %d frame %d", arch, g[1], args, maxspd, w[0], wantSPD)
					}
				}
				t.Logf("%s %s: %d frame records checked against the compiler", arch, name, found)
				if found == 0 {
					t.Fatalf("%s: no frame record of an example function in\n%s", name, lean)
				}
				if code, _, stderr := runJanus(t, "check", dir); code != 0 {
					t.Fatalf("check %s: %s", name, stderr)
				}
				if !strings.Contains(string(lean), "def frames : List Janus.Spec.Stack.FuncRec") {
					t.Fatalf("%s: no frames definition", name)
				}
			}
		})
	}
}
