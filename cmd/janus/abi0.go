package main

// Go assembly and the ABI wrappers (docs/ABI0.md): which calling convention the entry function
// of an extraction uses, so that the CLI can say it (extract, verify, explain, identity.json)
// and warn when a theorem states the other one.
//
// The classification is informational and untrusted, like reachability: it never changes what
// is extracted, and a theorem means what its statement says whatever is recorded here.

import (
	"fmt"
	"io"
	"regexp"
	"strings"
)

// Entry sources recorded in identity.json (entrySource).
const (
	sourceAssembly   = "assembly"    // a TEXT symbol of a Go assembly (.s) file
	sourceABIWrapper = "abi-wrapper" // a compiler-generated wrapper between ABIInternal and ABI0
)

// funcFile is the source file of the function at f.Addr in the pclntab ("" if unknown, e.g. C).
func (b *Binary) funcFile(f Func) string {
	tab, err := b.pclnTable()
	if err != nil || tab == nil {
		return ""
	}
	file, _, fn := tab.PCToLine(f.Addr)
	if fn == nil {
		return ""
	}
	return file
}

// hasFunc reports whether the binary defines a function named name.
func (b *Binary) hasFunc(name string) bool {
	for _, f := range b.Funcs {
		if f.Name == name {
			return true
		}
	}
	return false
}

// entryABI classifies f: its ABI ("ABI0" or "ABIInternal") and source (sourceAssembly or
// sourceABIWrapper) for Go assembly functions and the ABI wrappers; ("", "") for ordinary Go
// code (always ABIInternal), C code and anything else.
//
//   - a `.abi0` symbol from a `.s` file: Go assembly, ABI0;
//   - any other symbol from a `.s` file: Go assembly declared `<ABIInternal>` (runtime only);
//   - a `.abi0` symbol of `<autogenerated>` code: the ABI0 -> ABIInternal wrapper of a Go
//     function called from assembly (its entry follows ABI0);
//   - an `<autogenerated>` symbol `f` with an `f.abi0` sibling: the ABIInternal -> ABI0 wrapper
//     of the assembly function `f.abi0` (its entry follows ABIInternal).
func entryABI(b *Binary, f Func) (abi, source string) {
	if b == nil {
		return "", ""
	}
	file := b.funcFile(f)
	isABI0 := strings.HasSuffix(f.Name, ".abi0")
	switch {
	case strings.HasSuffix(file, ".s"):
		if isABI0 {
			return "ABI0", sourceAssembly
		}
		return "ABIInternal", sourceAssembly
	case file == "<autogenerated>" && isABI0:
		return "ABI0", sourceABIWrapper
	case file == "<autogenerated>" && b.hasFunc(f.Name+".abi0"):
		return "ABIInternal", sourceABIWrapper
	}
	return "", ""
}

// describeEntry is the parenthesised description of a classified entry ("" for Go code).
func describeEntry(abi, source string) string {
	switch {
	case source == sourceAssembly:
		return fmt.Sprintf("Go assembly, %s", abi)
	case source == sourceABIWrapper && abi == "ABI0":
		return "ABI wrapper: ABI0 entry calling the ABIInternal Go function"
	case source == sourceABIWrapper:
		return "ABI wrapper: ABIInternal entry calling the ABI0 assembly function"
	}
	return ""
}

// printEntryABI is the extract line about an assembly or wrapper entry.
func printEntryABI(w io.Writer, abi, source, goarch string) {
	d := describeEntry(abi, source)
	if d == "" {
		return
	}
	spec := "Janus.GoABI.Ensures"
	if abi == "ABI0" {
		spec = "Janus.GoABI0.Ensures0"
		if goarch == "amd64" {
			spec = "Janus.Amd64.GoABI0.Ensures0"
		}
	} else if goarch == "amd64" {
		spec = "Janus.Amd64.GoABI.Ensures"
	}
	how := "arguments and results in registers"
	if abi == "ABI0" {
		how = "arguments and results in the caller's frame at 8(RSP)"
	}
	fmt.Fprintf(w, "  entry: %s (%s); state theorems with %s (docs/ABI0.md)\n", d, how, spec)
}

// abi0Hint is the hint for a symbol that is missing while its `.abi0` assembly body exists.
func abi0Hint(b *Binary, sym string) string {
	if strings.HasSuffix(sym, ".abi0") || !b.hasFunc(sym+".abi0") {
		return ""
	}
	return fmt.Sprintf("\n  %s.abi0 exists: Go assembly is linked under its ABI0 name; the ABIInternal wrapper %s is only generated where Go code needs one, e.g. for a func value (docs/ABI0.md).", sym, sym)
}

// ensuresOnEntryRE matches the contract applied to the extraction's entry.
var ensuresOnEntryRE = regexp.MustCompile(`Janus\.(?:Amd64\.)?(GoABI0?)\.(Ensures\w*) Extracted\.program Extracted\.entry`)

// statementABI is the convention a theorem about the entry must use: the recorded one, else
// ABIInternal for every Go symbol that is not `.abi0` (ordinary Go code records nothing).
func statementABI(symbol, recorded string) string {
	if recorded != "" {
		return recorded
	}
	if strings.HasSuffix(symbol, ".abi0") {
		return "ABI0"
	}
	return "ABIInternal"
}

// abiMismatch is the warning for a statement whose contract on Extracted.entry uses the other
// calling convention than the entry function ("" when they agree or nothing is known).
func abiMismatch(statement, abi string) string {
	if abi == "" {
		return ""
	}
	for _, m := range ensuresOnEntryRE.FindAllStringSubmatch(statement, -1) {
		used := "ABIInternal"
		if m[1] == "GoABI0" {
			used = "ABI0"
		}
		if used != abi {
			return fmt.Sprintf("Warning: the entry function follows %s, but the statement uses %s.%s (%s) on Extracted.entry: its arguments are not where the code reads them, so the theorem is about calls the program does not make. See docs/ABI0.md.",
				abi, m[1], m[2], used)
		}
	}
	return ""
}
